//! Databases on a shared server: one login role and one database per resource, nothing else granted.
use serde::Deserialize;
use tokio_postgres::{Client, NoTls};

#[derive(Clone, Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SharedServer {
    pub id: String,
    pub label: String,
    /// Host and port customers connect to.
    pub host: String,
    pub port: u16,
    /// A role with CREATEROLE and CREATEDB on this server.
    pub admin_url: String,
    pub capacity: u32,
}
pub type Error = tokio_postgres::Error;
/// Identifiers and passwords are generated by the plugin (`wd_` + hex), never caller text.
fn ident(value: &str) -> &str {
    assert!(
        value.starts_with("wd_")
            && value.len() <= 63
            && value[3..]
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_'),
        "generated identifier"
    );
    value
}
/// A SCRAM-SHA-256 verifier computed here, so the server (and its logs) never see the password.
fn secret(value: &str) -> String {
    assert!(
        value.bytes().all(|b| b.is_ascii_hexdigit()),
        "generated password"
    );
    let verifier = postgres_protocol::password::scram_sha_256(value.as_bytes());
    assert!(
        !verifier.contains('\''),
        "verifier is base64 and separators only"
    );
    verifier
}
impl SharedServer {
    async fn admin(&self) -> Result<Client, Error> {
        let (client, connection) = tokio_postgres::connect(&self.admin_url, NoTls).await?;
        tokio::spawn(connection);
        Ok(client)
    }
    /// Run once per server at startup: no database is open to every role by default.
    pub async fn harden(&self) -> Result<(), Error> {
        self.admin()
            .await?
            .batch_execute(
                "REVOKE CONNECT ON DATABASE postgres FROM PUBLIC; REVOKE CONNECT ON DATABASE template1 FROM PUBLIC",
            )
            .await
    }
    pub async fn create(&self, database: &str, role: &str, password: &str) -> Result<(), Error> {
        let admin = self.admin().await?;
        let (database, role) = (ident(database), ident(role));
        admin
            .batch_execute(&format!(
                "CREATE ROLE {role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION CONNECTION LIMIT 20 PASSWORD '{}'",
                secret(password)
            ))
            .await?;
        // CREATE DATABASE cannot run inside a transaction block, so these are separate statements.
        let created = async {
            admin
                .batch_execute(&format!("CREATE DATABASE {database} OWNER {role}"))
                .await?;
            admin
                .batch_execute(&format!(
                    "REVOKE ALL ON DATABASE {database} FROM PUBLIC; GRANT CONNECT, TEMPORARY ON DATABASE {database} TO {role}"
                ))
                .await
        }
        .await;
        if created.is_err() {
            let _ = self.drop(database, role).await;
        }
        created
    }
    pub async fn password(&self, role: &str, password: &str) -> Result<(), Error> {
        self.admin()
            .await?
            .batch_execute(&format!(
                "ALTER ROLE {} PASSWORD '{}'",
                ident(role),
                secret(password)
            ))
            .await
    }
    pub async fn drop(&self, database: &str, role: &str) -> Result<(), Error> {
        let admin = self.admin().await?;
        admin
            .batch_execute(&format!(
                "DROP DATABASE IF EXISTS {} WITH (FORCE)",
                ident(database)
            ))
            .await?;
        admin
            .batch_execute(&format!("DROP ROLE IF EXISTS {}", ident(role)))
            .await
    }
}
